#!/usr/bin/env python3
"""Generates Sources/Features/Components/EnvelopeShape.swift from docs/design/brand/envelope.svg.

Takes the one `envelope-outline` path (M, C and Z only), normalises it to the unit square by the SVG viewBox,
and writes a SwiftUI Shape. The 5 MB of gradient rects in the SVG are the old flat shading and are not read.
Run: python3 tools/gen-envelope-shape.py [--check]   (--check exits 1 when the committed file differs)
"""
import os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SVG = os.path.join(ROOT, "docs/design/brand/envelope.svg")
OUT = os.path.join(ROOT, "Sources/Features/Components/EnvelopeShape.swift")

def build():
    head = open(SVG, encoding="utf-8").read(4000)
    vb = [float(v) for v in re.search(r'viewBox="([^"]+)"', head).group(1).split()]
    s = open(SVG, encoding="utf-8").read()
    d = re.search(r'<path id="envelope-outline"[^>]*?\sd="([^"]+)"', s).group(1)
    toks = re.findall(r"[MCZ]|-?\d+\.?\d*", d)
    x0, y0, w, h = vb
    def pt(i):
        return "p(%.5f, %.5f)" % ((float(toks[i]) - x0) / w, (float(toks[i + 1]) - y0) / h)
    lines, i = [], 0
    while i < len(toks):
        t = toks[i]
        if t == "M": lines.append("        path.move(to: %s)" % pt(i + 1)); i += 3
        elif t == "C": lines.append("        path.addCurve(to: %s, control1: %s, control2: %s)" % (pt(i + 5), pt(i + 1), pt(i + 3))); i += 7
        elif t == "Z": lines.append("        path.closeSubpath()"); i += 1
        else: raise SystemExit("unexpected token %r (a number without a command: the path uses an implicit repeat)" % t)
    return """// GENERATED by tools/gen-envelope-shape.py from docs/design/brand/envelope.svg. Do not edit: change the SVG or the script.
import SwiftUI

/// The brand envelope's silhouette, %d curves, in the SVG's own proportions (%.0f x %.0f). Fills whatever rect it is given,
/// so a caller keeps the aspect with `aspectRatio(EnvelopeShape.aspect, contentMode: .fit)`.
public struct EnvelopeShape: InsettableShape {
    public static let aspect: CGFloat = %.6f
    var inset: CGFloat = 0
    public init() {}
    public func inset(by amount: CGFloat) -> EnvelopeShape { var s = self; s.inset += amount; return s }
    public func path(in rect: CGRect) -> Path {
        let r = rect.insetBy(dx: inset, dy: inset)
        func p(_ x: CGFloat, _ y: CGFloat) -> CGPoint { CGPoint(x: r.minX + x * r.width, y: r.minY + y * r.height) }
        var path = Path()
%s
        return path
    }
}
""" % (sum(1 for l in lines if "addCurve" in l), w, h, w / h, "\n".join(lines))

if __name__ == "__main__":
    src = build()
    if "--check" in sys.argv:
        sys.exit(0 if os.path.exists(OUT) and open(OUT).read() == src else 1)
    open(OUT, "w").write(src); print("wrote", OUT, len(src), "bytes")
