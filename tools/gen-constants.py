#!/usr/bin/env python3
"""Derive Sources/CoreBridge/Generated/Constants.swift, core/crates/contracts/src/constants.rs and
relay/src/constants.rs (the RELAY_* rows only, so relay/ builds alone) from docs/CONSTANTS.md (every number lives once).

    python3 tools/gen-constants.py           write the file
    python3 tools/gen-constants.py --check   exit 1 when the committed file differs

Only rows whose value cells are plain numbers become constants; a row measured later (LIST_MIN_W) or
written in words is skipped and named in the file's header comment.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "docs", "CONSTANTS.md")
OUT = os.path.join(ROOT, "Sources", "CoreBridge", "Generated", "Constants.swift")
OUT_RS = os.path.join(ROOT, "core", "crates", "contracts", "src", "constants.rs")
OUT_RELAY = os.path.join(ROOT, "relay", "src", "constants.rs")
# A row written "A_B_C · D · E" names siblings by their last word; this is the family each sibling joins.
SIBLING_PREFIX = {"UNDO_SEND_DEFAULT_S": "UNDO_SEND", "SNOOZE_LATER_TODAY": "SNOOZE", "BACKFILL_CONCURRENT_MAC": "BACKFILL_CONCURRENT",
                  "GRAPH_CONCURRENT": "", "CHUNK_TOKENS": ""}
NUM = re.compile(r"^\s*(\d[\d,]*(?:\.\d+)?)")


def rows():
    for line in open(SRC, encoding="utf-8"):
        if not line.startswith("| ") or line.startswith("| Constant") or line.startswith("|---"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 2:
            continue
        names = [n.strip() for n in re.split(r"[·/]", cells[0])]
        vals = [v.strip() for v in cells[1].split("·")] if "·" in cells[1] else [v.strip() for v in cells[1].split("/")]
        if len(vals) != len(names):
            vals = [cells[1]] * len(names)
        family = SIBLING_PREFIX.get(names[0].split(" (")[0].strip(), "")
        for i, (n, v) in enumerate(zip(names, vals)):
            ident = n.split(" (")[0].strip()
            if not re.fullmatch(r"[A-Z][A-Z0-9_]*", ident):
                continue
            if i > 0 and family and "_" not in ident or (i > 0 and family and not ident.startswith(family)):
                ident = family + "_" + ident
            m = NUM.match(v) if ":" not in v else None
            yield ident, (m.group(1).replace(",", "") if m else None), v


def numeric():
    seen, out, skipped = set(), [], []
    for ident, num, raw in rows():
        if ident in seen:
            continue
        seen.add(ident)
        (skipped if num is None else out).append((ident, num) if num is not None else ident)
    return out, skipped


def render_rs(prefix=None):
    out, skipped = numeric()
    if prefix:
        out = [(i, n) for i, n in out if i.startswith(prefix)]
        skipped = [i for i in skipped if i.startswith(prefix)]
    lines = ["pub const %s: %s = %s;" % (i, "f64" if "." in n else "u64", n if "." in n else "{:_}".format(int(n))) for i, n in out]
    scope = " (rows starting %s only; relay/ builds alone)" % prefix if prefix else ""
    return ("//! GENERATED by tools/gen-constants.py from docs/CONSTANTS.md%s. Do not edit: change the ledger.\n"
            "//! Not numeric at this commit (skipped): %s\n" % (scope, ", ".join(skipped) or "none")) + "\n".join(lines) + "\n"


def render():
    out, skipped = [], []
    seen = set()
    for ident, num, raw in rows():
        if ident in seen:
            continue
        seen.add(ident)
        if num is None:
            skipped.append(ident)
            continue
        out.append("    public static let %s: %s = %s" % (ident, "Double" if "." in num else "Int", num))
    head = ("// GENERATED by tools/gen-constants.py from docs/CONSTANTS.md. Do not edit: change the ledger.\n"
            "// Not numeric at this commit (skipped): %s\n" % (", ".join(skipped) or "none"))
    return head + "public enum WhooshConstants {\n" + "\n".join(out) + "\n}\n"


if __name__ == "__main__":
    targets = [(OUT, render()), (OUT_RS, render_rs()), (OUT_RELAY, render_rs("RELAY_"))]
    if "--check" in sys.argv:
        bad = [p for p, text in targets if (open(p, encoding="utf-8").read() if os.path.exists(p) else "") != text]
        for p in bad:
            print("DRIFT: %s differs from docs/CONSTANTS.md; run tools/gen-constants.py" % os.path.relpath(p, ROOT))
        if not bad:
            print("constants match docs/CONSTANTS.md (Swift, core Rust and relay Rust)")
        sys.exit(1 if bad else 0)
    for p, text in targets:
        os.makedirs(os.path.dirname(p), exist_ok=True)
        open(p, "w", encoding="utf-8").write(text)
        print("wrote %s" % os.path.relpath(p, ROOT))
