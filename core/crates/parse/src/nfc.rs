fn compose(base: char, mark: char) -> Option<char> {
    let (b, m) = (base as u32, mark as u32);
    // Hangul: L + V, then LV + T
    if (0x1100..0x1113).contains(&b) && (0x1161..0x1176).contains(&m) { return char::from_u32(0xAC00 + ((b - 0x1100) * 21 + (m - 0x1161)) * 28); }
    if (0xAC00..0xD7A4).contains(&b) && (b - 0xAC00) % 28 == 0 && (0x11A8..0x11C3).contains(&m) { return char::from_u32(b + (m - 0x11A7)); }
    PAIRS.binary_search_by(|(pb, pm, _)| (*pb, *pm).cmp(&(b, m))).ok().and_then(|i| char::from_u32(PAIRS[i].2))
}

/// `s` in NFC. Plain ASCII and text with no combining mark are returned as they are.
pub fn nfc(s: &str) -> String {
    if s.is_ascii() || !s.chars().any(|c| ('\u{300}'..='\u{36F}').contains(&c) || ('\u{1100}'..='\u{11FF}').contains(&c) || ('\u{3099}'..='\u{309A}').contains(&c) || ('\u{0653}'..='\u{0655}').contains(&c)) { return s.to_string(); }
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        if let Some(prev) = out.chars().next_back() {
            if let Some(joined) = compose(prev, c) { out.pop(); out.push(joined); continue; }
        }
        out.push(c);
    }
    out
}

#[cfg(test)]
mod tests {
    use super::nfc;
    #[test]
    fn a_letter_and_its_accent_become_one_character() {
        assert_eq!(nfc("cafe\u{301} Cre\u{300}me n\u{303}"), "caf\u{e9} Cr\u{e8}me \u{f1}");
        assert_eq!(nfc("a\u{30a}ngstro\u{308}m"), "\u{e5}ngstr\u{f6}m");
        assert_eq!(nfc("\u{1100}\u{1161}\u{11a8}"), "\u{ac01}");
    }
    #[test]
    fn text_already_composed_or_plain_is_returned_unchanged() {
        for s in ["plain ascii", "d\u{e9}j\u{e0} vu", "\u{4e2d}\u{6587}", ""] { assert_eq!(nfc(s), s); }
    }
}
