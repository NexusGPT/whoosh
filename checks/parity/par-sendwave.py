#!/usr/bin/env python3
"""par-sendwave: the send shockwave (docs/PRD.md "## Send shockwave: a halo spreads from the send button").

A send in the quick reply and in the composer starts the wave AFTER the send: the outbox entry exists while the wave
still runs, the next socket request is not held by it, its run is SENDWAVE_MS in the ledger's scheme, an undo ends it
at once, its frames stay under FRAME_MS, and reduced motion turns it off.

Run (fixture core):
  sh scripts/launch-one.sh <bundle> -- --fixture-core sh -c 'WHOOSH_SOCKET_DIR="$D" python3 checks/parity/par-sendwave.py'
  reduced motion: LAUNCH_ENV="WHOOSH_REDUCE_MOTION=1" sh scripts/launch-one.sh <bundle> -- --fixture-core \
      sh -c 'WHOOSH_SOCKET_DIR="$D" python3 checks/parity/par-sendwave.py --reduced-motion'
  the shader's bytes:   python3 checks/parity/par-sendwave.py --compile-shader   (regenerates the metallib Swift file)
  static only:          python3 checks/parity/par-sendwave.py --static
Prints the MUTANTS table then 'N checks, F failed, U not judged'; exit 1 when F > 0 or U > 0.

MUTANTS (each seen red, recorded in _captures/sendwave/mutants.txt):
| mutant | how | check that goes red |
| never | LAUNCH_ENV="WHOOSH_MUTANT_SENDWAVE=never" | quickreply-wave-runs, composer-wave-runs |
| gate  | LAUNCH_ENV="WHOOSH_MUTANT_SENDWAVE=gate"  | quickreply-next-request-not-held, quickreply-sent-while-wave-runs |
| stale shader | edit the shader source without --compile-shader | shader-bytes-match-source |
| freeze-button | LAUNCH_ENV="WHOOSH_MUTANT_SENDWAVE=freeze-button" | quickreply-button-live |
| gate-landing | LAUNCH_ENV="WHOOSH_MUTANT_SENDWAVE=gate-landing" | quickreply-landing-never-holds-a-key |
| ignore-motion | LAUNCH_ENV="WHOOSH_REDUCE_MOTION=1 WHOOSH_MUTANT_SENDWAVE=ignore-motion" with --reduced-motion | reduced-motion-off |
| load-ignored | held_verdict judges a slow reply whatever the load (this file, --static) | next-request-verdict-follows-load |
"""
import base64
import glob
import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile
import time

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import importlib.util as _ilu
_sw = _ilu.spec_from_file_location("shotwait", os.path.join(ROOT, "journeys", "lib", "shotwait.py")); shotwait = _ilu.module_from_spec(_sw); _sw.loader.exec_module(shotwait)   # how long a `shot` reply may take (one place)
SW = os.path.join(ROOT, "Sources", "Design", "SendWave")
SOURCE = os.path.join(SW, "SendWaveShaderSource.swift")
LIBRARY = os.path.join(SW, "SendWaveShaderLibrary.swift")
REGION = "mac-main.sendwave"


def ledger():
    vals = {}
    for line in open(os.path.join(ROOT, "docs", "CONSTANTS.md"), encoding="utf-8"):
        m = re.match(r"\|\s*([A-Z0-9_ /]+?)\s*\|\s*([^|]+?)\s*\|", line)
        if m:
            for name in m.group(1).split(" / "):   # a row may carry two names for one value
                vals.setdefault(name.strip(), m.group(2))   # the first row is the value; later tables describe it
    return vals


def shader_source():
    s = open(SOURCE, encoding="utf-8").read()
    return re.search(r'#"""\n(.*?)\n"""#', s, re.S).group(1)


def compile_shader():
    src = shader_source()
    digest = hashlib.sha256(src.encode()).hexdigest()
    with tempfile.TemporaryDirectory() as d:
        m, air, lib = (os.path.join(d, n) for n in ("w.metal", "w.air", "w.metallib"))
        open(m, "w").write(src)
        subprocess.run(["xcrun", "-sdk", "macosx", "metal", "-mmacosx-version-min=15.0", "-c", m, "-o", air], check=True)
        subprocess.run(["xcrun", "-sdk", "macosx", "metallib", air, "-o", lib], check=True)
        data = base64.b64encode(open(lib, "rb").read()).decode()
    lines = [data[i:i + 120] for i in range(0, len(data), 120)]
    body = "\n".join(lines)
    out = ("import Foundation\n\n"
           "/// GENERATED by `python3 checks/parity/par-sendwave.py --compile-shader` from SendWaveShaderSource.text\n"
           "/// (xcrun metal, macOS 15 minimum). Never edited by hand: par-sendwave compares the digest to the source.\n"
           "enum SendWaveShaderLibrary {\n"
           f"    static let sourceSHA256 = \"{digest}\"\n"
           "    static let metallib: Data = Data(base64Encoded: base64, options: .ignoreUnknownCharacters) ?? Data()\n"
           f"    private static let base64 = \"\"\"\n{body}\n\"\"\"\n"
           "}\n")
    open(LIBRARY, "w").write(out)
    print(f"wrote {LIBRARY} ({len(data)} base64 chars, source sha256 {digest[:12]})")


class Tally:
    def __init__(self):
        self.n = self.f = self.u = 0
        self.lines = []

    def check(self, name, ok, detail=""):
        self.n += 1
        if ok is None:
            self.u += 1; verdict = "NOT JUDGED"
        elif ok:
            verdict = "ok"
        else:
            self.f += 1; verdict = "FAIL"
        line = f"{verdict:10} {name}  {detail}"
        self.lines.append(line); print(line, flush=True)


def held_verdict(load, load_max, commit, ms, rtt):
    """None (not judged) when a slow reply was taken under a load above PERF_LOAD_MAX and is shorter than the wave itself; else whether the reply came within the commit budget."""
    return None if (load > load_max and commit <= rtt < ms) else rtt < commit


def static_checks(t):
    led0 = ledger()
    commit0, ms0, lmax0 = float(led0["INTERACTION_COMMIT_MS"]), float(led0["SENDWAVE_MS"]), float(led0["PERF_LOAD_MAX"])
    t.check("next-request-verdict-follows-load",
            (held_verdict(lmax0 + 6, lmax0, commit0, ms0, commit0 + 10), held_verdict(lmax0 - 6, lmax0, commit0, ms0, commit0 + 10),
             held_verdict(lmax0 - 6, lmax0, commit0, ms0, commit0 - 10), held_verdict(lmax0 + 6, lmax0, commit0, ms0, ms0 + 10)) == (None, False, True, False),
            f"slow reply: over the load budget not judged, under it red; a fast one green; a reply held as long as the wave red (PERF_LOAD_MAX {lmax0:g}, INTERACTION_COMMIT_MS {commit0:g}, SENDWAVE_MS {ms0:g})")
    lib = open(LIBRARY, encoding="utf-8").read() if os.path.exists(LIBRARY) else ""
    m = re.search(r'sourceSHA256 = "([0-9a-f]+)"', lib)
    digest = hashlib.sha256(shader_source().encode()).hexdigest()
    t.check("shader-bytes-match-source", bool(m) and m.group(1) == digest,
            f"library {m.group(1)[:12] if m else 'missing'} vs source {digest[:12]}")
    led = ledger()
    scheme = open(os.path.join(SW, "SendWaveScheme.swift"), encoding="utf-8").read()
    dm = re.search(r"ledgerDefault: SendWaveScheme = \.(\w+)", scheme)
    t.check("scheme-default-is-ledger", bool(dm) and dm.group(1) == led.get("SENDWAVE_SCHEME"),
            f"code {dm.group(1) if dm else None} ledger {led.get('SENDWAVE_SCHEME')}")
    src = shader_source()
    t.check("shader-loops-ledger-ring-count", "for (int i = 0; i < 4; i++)" in src and led.get("SENDWAVE_RINGS") == "4",
            f"ledger SENDWAVE_RINGS={led.get('SENDWAVE_RINGS')}")


class Ctl:
    def __init__(self, sock):
        self.sock = sock

    def call(self, verb, *args):
        import socket
        s = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
        s.settimeout(shotwait.timeout_for(verb, args, 30))
        s.connect(self.sock)
        s.sendall((json.dumps({"verb": verb, "args": [str(a) for a in args]}) + "\n").encode())
        buf = b""
        while not buf.endswith(b"\n"):
            chunk = s.recv(65536)
            if not chunk:
                break
            buf += chunk
        s.close()
        return json.loads(buf.decode())

    def timed(self, verb, *args):
        t0 = time.perf_counter()
        r = self.call(verb, *args)
        return r, (time.perf_counter() - t0) * 1000

    def wave(self, pane):
        r = self.call("rows", REGION)
        if not r.get("ok"):
            return None
        for row in r.get("rows", []):
            if row.get("pane") == pane:
                return row
        return {}

    def outbox(self):
        r = self.call("core", "state", "outbox_entry/count")
        return int(r["value"]) if r.get("ok") else None


def wait_done(c, pane, run, limit_s):
    end = time.time() + limit_s
    row = c.wave(pane)
    while time.time() < end and row and row.get("run") == run and row.get("state") == "running":
        time.sleep(0.05)
        row = c.wave(pane)
    return row


def settle(c, frame):
    """A person types before sending: wait until the app answers within FRAME_MS twice in a row (the pane's own
    opening animation and first loads are over), so the frames measured are the wave's, not the pane's arrival."""
    end, calm = time.time() + 10, 0
    while time.time() < end and calm < 2:
        _, ms = c.timed("uistate")
        calm = calm + 1 if ms < frame else 0


def load_now():
    return os.getloadavg()[0]


PIXEL_TOLERANCE = 12   # per channel, of 255: PNG and compositing noise between two shots of one unchanged control


def pixel(path, x, y):
    out = subprocess.run(["/opt/homebrew/bin/ffmpeg", "-v", "error", "-i", path, "-vf", "crop=1:1:%d:%d" % (x, y),
                          "-f", "rawvideo", "-pix_fmt", "rgb24", "-"], capture_output=True, check=True).stdout
    return tuple(out[:3])


def button_live(t, c, name, pane, button, prev_run):
    """Inside the halo the send button must be the LIVE control. Two halves: the rectangle the effect leaves out is
    the measured button, and in the app's own rendered frames (WHOOSH_SENDWAVE_RECORD; no screen is read) the
    button's pixel in the first frame of the wave equals the same pixel in the last (the picture under the glass);
    a button drawn from the picture is tinted and bent by the halo, so the first frame differs."""
    m = c.call("measure", button)
    if not m.get("ok"):
        t.check(f"{name}-button-live", None, "measure %s: %s" % (button, m.get("error")))
        return
    f = m["frame"]
    end = time.time() + 2
    row = c.wave(pane)
    while time.time() < end and not ((row or {}).get("run") != prev_run and (row or {}).get("snapshot_source")):
        row = c.wave(pane)
    wait_done(c, pane, (row or {}).get("run"), 4)
    same_rect = all(abs((row or {}).get("live_" + k, -9) - f[k]) <= 0.5 for k in ("w", "h"))
    rec = os.environ.get("SENDWAVE_RECORD_DIR")
    pattern = os.path.join(rec or "", "[0-9][0-9]-Whoosh-[0-9]*.png")
    last, still, end = -1, 0, time.time() + 10      # the app's frames are written off its main thread and land late
    while rec and time.time() < end and still < 2:
        n = len(glob.glob(pattern)); still = still + 1 if n == last else 0; last = n; time.sleep(0.5)
    frames = sorted(glob.glob(pattern)) if rec else []
    if not frames:
        t.check(f"{name}-button-live", None if same_rect else False,
                "left out %sx%s vs button %sx%s; no rendered frames (SENDWAVE_RECORD_DIR unset or empty): pixel half not judged" % (
                    (row or {}).get("live_w"), (row or {}).get("live_h"), f["w"], f["h"]))
        return
    run = max(os.path.basename(x)[:2] for x in frames)
    mine = sorted((x for x in frames if os.path.basename(x)[:2] == run), key=lambda x: int(x.rsplit("-", 1)[1][:-4]))
    scale = 2
    x, y = int((f["x"] + f["w"] - f["h"] / 2) * scale), int((f["y"] + f["h"] / 2) * scale)
    a, b = pixel(mine[0], x, y), pixel(mine[-1], x, y)
    live = same_rect and max(abs(i - j) for i, j in zip(a, b)) <= PIXEL_TOLERANCE
    t.check(f"{name}-button-live", live, "left out %sx%s vs button %sx%s; rendered frame %s first %s last %s" % (
        (row or {}).get("live_w"), (row or {}).get("live_h"), f["w"], f["h"], run, a, b))


def landing_holds_no_key(t, c, led, name):
    """A send left to land: when the undo window closes the card lands (quickreply's ThreadLift plays AuroraLanding).
    While the landing runs, every request is answered at once and a key (J) is applied: the light never holds a key.
    Not judged while no landing runs in this build (the ThreadLift hook is quickreply's)."""
    commit = float(led["INTERACTION_COMMIT_MS"])
    window_s = float(led.get("UNDO_SEND_DEFAULT_S", "10")) + 5
    c.call("type", " to land")
    c.call("key", "⌘Enter")
    end, rtts, seen, pressed, before, after = time.time() + window_s, [], None, False, None, None
    while time.time() < end:
        r, ms = c.timed("rows", REGION)
        landing = [x for x in (r.get("rows") or []) if x.get("kind") == "landing"]
        if landing:
            seen = landing[-1]
            rtts.append(ms)
            if not pressed and seen.get("state") == "running":
                before = (c.call("uistate").get("state") or {}).get("focus_index")
                k, kms = c.timed("key", "J"); rtts.append(kms); pressed = True
                after = (c.call("uistate").get("state") or {}).get("focus_index")
            if seen.get("state") in ("done", "interrupted"):
                break
        time.sleep(0.03)
    if not seen:
        t.check(f"{name}-landing-never-holds-a-key", None, "not judged: no landing ran within %.0f s (ThreadLift's AuroraLanding hook not in this build)" % window_s)
        return
    worst = max(rtts) if rtts else 0
    t.check(f"{name}-landing-never-holds-a-key", pressed and worst < commit and before != after,
            "landing %s; longest reply during it %.1f ms (INTERACTION_COMMIT_MS %g); J moved focus %s -> %s" % (
                seen.get("state"), worst, commit, before, after))


def drive_pane(t, c, led, name, pane, open_steps, send_key, undo_key, button=None):
    ms = float(led["SENDWAVE_MS"]); frame = float(led["FRAME_MS"]); commit = float(led["INTERACTION_COMMIT_MS"])
    load_max = float(led["PERF_LOAD_MAX"])
    for verb, *args in open_steps:
        c.call(verb, *args)
    settle(c, frame)
    load = load_now()
    before = c.outbox()
    prev = c.wave(pane)
    if prev is None:
        t.check(f"{name}-region-served", None, f"rows {REGION} answers not ok (SendWaveFeature not registered?)")
        return
    prev_run = (prev or {}).get("run")
    r, key_ms = c.timed("key", send_key)
    after, rtt = c.timed("rows", REGION)
    out = c.outbox()
    t.check(f"{name}-send-key-taken", r.get("ok"), json.dumps(r)[:120])
    # under load a slow reply is not judged, but a reply held as long as the wave itself is the wave holding it
    held = held_verdict(load, load_max, commit, ms, rtt)
    t.check(f"{name}-next-request-not-held", held, f"rows round trip {rtt:.1f} ms after the send key (INTERACTION_COMMIT_MS {commit:g}); "
            f"load {load:.1f} (PERF_LOAD_MAX {load_max:g}), SENDWAVE_MS {ms:g}" + ("; not judged: the load is over the budget and the reply is shorter than the wave" if held is None else ""))
    t.check(f"{name}-sent-on-key", None if before is None or out is None else out - before == 1,
            f"outbox {before} -> {out} on the reply to the key")
    row = c.wave(pane)
    running = bool(row) and row.get("run") != prev_run and row.get("state") == "running"
    t.check(f"{name}-wave-runs", running, json.dumps({k: (row or {}).get(k) for k in ("state", "run", "elapsed_ms", "reason")}))
    t.check(f"{name}-sent-while-wave-runs", running and out is not None and before is not None and out - before == 1
            and (row or {}).get("elapsed_ms", ms) < ms, f"outbox +{(out or 0) - (before or 0)} with the wave at {(row or {}).get('elapsed_ms', -1):.0f} ms of {ms:g}")
    t.check(f"{name}-scheme-is-ledger", (row or {}).get("scheme") == led.get("SENDWAVE_SCHEME"), f"{(row or {}).get('scheme')}")
    run = (row or {}).get("run")
    done = wait_done(c, pane, run, ms / 1000 * 4)
    el = (done or {}).get("elapsed_ms", 0)
    t.check(f"{name}-wave-ends-on-time", (done or {}).get("state") == "done" and ms * 0.9 <= el <= ms * 1.25,
            f"state {(done or {}).get('state')} after {el:.0f} ms (SENDWAVE_MS {ms:g})")
    ok = (done or {}).get("frames", 0) > 0 and (done or {}).get("max_busy_ms", 99) < frame and (done or {}).get("dropped", 1) == 0
    # the hidden rig draws the picture on the main thread (its windows are at alpha 0): the frame verdict is the owner's
    # copy's (perf/sendwave-report.py), never this rig's
    hidden = os.environ.get("WHOOSH_RIG_HIDDEN") == "1"
    t.check(f"{name}-frames-under-budget", None if hidden else (ok if load <= load_max else None),
            ("not judged: hidden (the picture is drawn on the main thread in the hidden rig; the verdict is "
             "perf/sendwave-report.py on the owner's copy) " if hidden else "") +
            "load {:.1f} (PERF_LOAD_MAX {:g}) frames {} dropped {} max_busy {:.1f} ms max_interval {:.1f} ms nominal {:.1f} ms snapshot {:.1f} ms ({})".format(
                load, load_max, (done or {}).get("frames"), (done or {}).get("dropped"), (done or {}).get("max_busy_ms", -1),
                (done or {}).get("max_frame_ms", -1), (done or {}).get("nominal_frame_ms", -1),
                (done or {}).get("snapshot_ms", -1), (done or {}).get("snapshot_source")))
    if undo_key:
        # undo the first send, send again, and undo while this wave runs: the wave ends at once, the send is cancelled
        c.call("key", undo_key)
        c.call("type", " again")
        c.call("key", send_key)
        row = c.wave(pane)
        c.call("key", undo_key)
        cut = c.wave(pane)
        t.check(f"{name}-undo-interrupts", (row or {}).get("state") == "running" and (cut or {}).get("state") == "interrupted",
                f"{(row or {}).get('state')} -> {(cut or {}).get('state')} ({(cut or {}).get('reason')})")
    if button:
        # a separate send, so the shots it takes never weigh on the frames measured above
        c.call("type", " once more")
        prev = (c.wave(pane) or {}).get("run")
        c.call("key", send_key)
        button_live(t, c, name, pane, button, prev)
        c.call("key", undo_key)
        landing_holds_no_key(t, c, led, name)


def live(t, sock, reduced):
    c = Ctl(sock)
    led = ledger()
    c.call("fixture", "reset")
    qr_open = [("key", "R"), ("type", "Thanks, sent with a wave")]
    if reduced:
        for verb, *args in qr_open:
            c.call(verb, *args)
        c.call("key", "⌘Enter")
        row = c.wave("mac-main.reply")
        t.check("reduced-motion-off", None if row is None else (row or {}).get("state") == "off",
                json.dumps({k: (row or {}).get(k) for k in ("state", "reason")}))
        return
    drive_pane(t, c, led, "quickreply", "mac-main.reply", qr_open, "⌘Enter", "Z", button="mac-main.quickreply.send")
    # close the quick reply first: while it is open it holds ⌘Enter (seen in the hidden rig: the composer's send
    # went to the quick reply), and this check is about the composer's wave
    c.call("key", "Escape")
    c.call("fixture", "reset")
    composer_open = [("click", "mac-main.reader.open-full-composer"), ("type", "Thanks Karen, sent with a wave.")]
    drive_pane(t, c, led, "composer", "mac-composer.body", composer_open, "⌘Enter", "Z")


def main():
    if "--compile-shader" in sys.argv:
        compile_shader(); return 0
    t = Tally()
    static_checks(t)
    if "--static" not in sys.argv:
        d = os.environ.get("WHOOSH_SOCKET_DIR")
        sock = os.path.join(d, "whoosh.sock") if d else None
        if not sock or not os.path.exists(sock):
            t.check("socket", None, "no socket: run under scripts/launch-one.sh")
        else:
            live(t, sock, "--reduced-motion" in sys.argv)
    print("MUTANTS (" + __doc__.split("MUTANTS (")[1].split('"""')[0].strip())
    print(f"{t.n} checks, {t.f} failed, {t.u} not judged")
    return 1 if t.f or t.u else 0


if __name__ == "__main__":
    sys.exit(main())
